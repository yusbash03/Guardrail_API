public static class CategoryCodes
{
    public const string Groceries = "GROCERIES";
    public const string Household = "HOUSEHOLD";
    public const string PersonalCare = "PERSONAL_CARE";
    public const string Baby = "BABY";
    public const string Electronics = "ELECTRONICS";
    public const string Alcohol = "ALCOHOL";

    public static readonly IReadOnlyList<string> All = [Groceries, Household, PersonalCare, Baby, Electronics, Alcohol];

    public static string DisplayName(string code) => code switch
    {
        Groceries => "groceries",
        Household => "household",
        PersonalCare => "personal care",
        Baby => "baby",
        Electronics => "electronics",
        Alcohol => "alcohol",
        _ => code.ToLowerInvariant().Replace('_', ' '),
    };
}

